// Чтение неориентированного графа в сжатые списки смежности — общая часть решений.
const READ_GRAPH = String.raw`
static int vertices, edges;
static int from[200000], to[200000];
static int start[100002], fill[100001], adj[400000];

static int read_graph(void) {
    if (scanf("%d %d", &vertices, &edges) != 2 || vertices < 1 || vertices > 100000 ||
        edges < 0 || edges > 200000) {
        return 0;
    }
    for (int i = 0; i < edges; i++) {
        if (scanf("%d %d", &from[i], &to[i]) != 2) {
            return 0;
        }
        start[from[i] + 1]++;
        start[to[i] + 1]++;
    }
    for (int v = 1; v <= vertices + 1; v++) {
        start[v] += start[v - 1];
    }
    for (int v = 1; v <= vertices; v++) {
        fill[v] = start[v];
    }
    for (int i = 0; i < edges; i++) {
        adj[fill[from[i]]++] = to[i];
        adj[fill[to[i]]++] = from[i];
    }
    return 1;
}`;

