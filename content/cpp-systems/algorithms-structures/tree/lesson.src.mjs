const READ_TREE = String.raw`
typedef struct Node {
    int value;
    struct Node *left;
    struct Node *right;
} Node;

// Читает дерево: n, затем n строк «значение левый правый». Возвращает корень или NULL.
static Node *read_tree(void) {
    int n;
    if (scanf("%d", &n) != 1 || n < 1 || n > 1000) {
        return NULL;
    }
    static Node *nodes[1000];
    static int left[1000], right[1000];
    for (int i = 0; i < n; i++) {
        nodes[i] = malloc(sizeof *nodes[i]);
        if (nodes[i] == NULL) {
            exit(1);
        }
        if (scanf("%d %d %d", &nodes[i]->value, &left[i], &right[i]) != 3) {
            exit(1);
        }
    }
    for (int i = 0; i < n; i++) {
        nodes[i]->left = left[i] >= 0 ? nodes[left[i]] : NULL;
        nodes[i]->right = right[i] >= 0 ? nodes[right[i]] : NULL;
    }
    return nodes[0];
}`;

