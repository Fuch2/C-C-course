function exercise(data, id) {
  const functionMode = typeof data.cases[0][0] === 'number';
  const tests = data.cases.map((c, i) => ({
    id: `case-${i + 1}`,
    name: i < 2 ? `Пример ${i + 1}` : `Граничный сценарий ${i - 1}`,
    ...(functionMode
      ? { arguments: c.slice(0, 2), expected: `${c[2]}\n` }
      : { stdin: c[0], expected: c[1] }),
  }));
  return {
    id,
    title: data.title,
    description: data.task,
    difficulty: 'advanced',
    language: 'cpp',
    standard: 'c++20',
    compiler: 'clang',
    diagnostics: 'sanitizers',
    starterCode:
      data.starter ??
      '#include <memory>\n#include <vector>\n\n// Реализуйте описанные в условии типы и их методы.\nint solve(int a, int b) {\n    (void)a; (void)b;\n    return 0;\n}\n',
    examples: tests.slice(0, 2).map((t) => ({
      input: t.stdin ?? `solve(${t.arguments.join(', ')})`,
      output: t.expected,
      explanation:
        'Результат следует из контракта задания; проверьте порядок действий и состояние объектов.',
    })),
    constraints: functionMode
      ? [
          'Аргументы a, b — целые от −1000 до 1000 включительно.',
          'Соблюдайте имена, сигнатуры, владение и доступ из условия.',
          'Функцию main добавляет система. Возвращайте результат из solve, не печатайте его.',
        ]
      : [
          'C++20. Один файл с готовым консольным адаптером.',
          'Границы, входной протокол и поведение API заданы в условии.',
          'Память датчиков принадлежит процессору; не используйте ручные new/delete.',
        ],
    hints: [
      {
        id: 'hint-1',
        order: 1,
        text:
          data.hint ??
          'Разделите поля состояния и публичные операции из условия. Сначала реализуйте один объект, затем вызов через требуемый интерфейс.',
      },
      {
        id: 'hint-2',
        order: 2,
        text:
          data.explanation ??
          'Проследите все вызовы solve по порядку. Проверьте отрицательные аргументы, ноль и границы; соблюдайте const, чтобы наблюдение не меняло состояние.',
      },
    ],
    publicTests: tests.slice(0, 2),
    hiddenTests: tests.slice(2),
    referenceSolution: data.solution,
    solutionExplanation:
      data.explanation ??
      `${data.task} В эталоне каждый шаг выражен методом соответствующего типа; solve только соединяет операции. ${data.mistake} Время и дополнительная память этого упражнения O(1): число объектов и вызовов фиксировано.`,
    checking: functionMode
      ? {
          type: 'function',
          functionName: 'solve',
          returnType: 'int',
          parameters: [
            { name: 'a', type: 'int' },
            { name: 'b', type: 'int' },
          ],
        }
      : { type: 'stdout', comparison: 'exact' },
  };
}
